SECTORS: list[str] = [
    "Обрабатывающая промышленность",
    "Добыча",
    "ИТ и связь",
    "Финансы и услуги",
    "Торговля",
    "Строительство",
    "Транспорт",
    "Сельское хозяйство",
]

SECTOR_BASE_SHARE: dict[str, float] = {
    "Обрабатывающая промышленность": 0.26,
    "Добыча": 0.07,
    "ИТ и связь": 0.06,
    "Финансы и услуги": 0.18,
    "Торговля": 0.17,
    "Строительство": 0.08,
    "Транспорт": 0.11,
    "Сельское хозяйство": 0.07,
}

SECTOR_GROWTH: dict[str, float] = {
    "Обрабатывающая промышленность": 0.025,
    "Добыча": 0.015,
    "ИТ и связь": 0.085,
    "Финансы и услуги": 0.055,
    "Торговля": 0.040,
    "Строительство": 0.030,
    "Транспорт": 0.028,
    "Сельское хозяйство": 0.020,
}

COVID_DIP = {2020: -0.035, 2021: 0.045}


def _sector_mix(specialty: str, rng: np.random.Generator) -> dict[str, float]:
    """Возвращает доли отраслей в ВРП города с учётом специализации."""
    shares = {s: SECTOR_BASE_SHARE[s] for s in SECTORS}
    boost = rng.uniform(1.8, 2.4)
    shares[specialty] *= boost
    for s in SECTORS:
        if s != specialty:
            shares[s] *= rng.uniform(0.85, 1.05)
    total = sum(shares.values())
    return {s: v / total for s, v in shares.items()}


@st.cache_data(show_spinner=False)
def build_panel() -> pd.DataFrame:
    """Строит длинный датасет (город × год × отрасль)."""
    rng = np.random.default_rng(SEED)
    rows: list[dict] = []
    years = range(START_YEAR, END_YEAR + 1)

    for idx, city in enumerate(CITIES):
        mix = _sector_mix(city.specialty, rng)
        pop_growth = rng.normal(0.004, 0.002)
        labour_share = rng.uniform(0.45, 0.53)

        for year in years:
            t = year - START_YEAR
            pop = city.pop_mln_2010 * (1 + pop_growth) ** t
            total_employment = pop * labour_share * 1000  # тыс. чел.

            for sector in SECTORS:
                sector_share = mix[sector] * (1 + rng.normal(0, 0.01))
                g = SECTOR_GROWTH[sector] + rng.normal(0, 0.012)
                cycle = 0.015 * np.sin((t + idx % 7) / 2.3)
                grp = city.base_grp_mrd * sector_share * (1 + g + cycle) ** t
                grp *= 1 + COVID_DIP.get(year, 0.0) * (
                    1.5 if sector in ("Транспорт", "Торговля", "Строительство") else 0.8
                )

                employment_share = sector_share * rng.uniform(0.85, 1.15)
                employment = total_employment * employment_share

                wage = 35 + rng.normal(0, 3)
                wage *= {
                    "Финансы и услуги": 2.1, "ИТ и связь": 2.4, "Добыча": 2.2,
                    "Транспорт": 1.1, "Обрабатывающая промышленность": 1.05,
                    "Торговля": 0.95, "Строительство": 1.0, "Сельское хозяйство": 0.75,
                }[sector]
                wage *= (1 + 0.07) ** t  # номинальная индексация

                investment = grp * rng.uniform(0.12, 0.22)

                rows.append({
                    "город": city.name,
                    "округ": city.fd,
                    "широта": city.lat,
                    "долгота": city.lon,
                    "год": year,
                    "отрасль": sector,
                    "население_млн": pop,
                    "занятость_тыс": employment,
                    "ВРП_млрд": grp,
                    "средняя_з/п_тыс": wage,
                    "инвестиции_млрд": investment,
                })

    df = pd.DataFrame(rows)
    df["производительность_млн_на_чел"] = df["ВРП_млрд"] * 1e3 / df["занятость_тыс"]
    return df


@st.cache_data(show_spinner=False)
def city_year_panel() -> pd.DataFrame:
    """Агрегирует до уровня (город × год), убирая отрасли."""
    df = build_panel()
    agg = (
        df.groupby(["город", "округ", "широта", "долгота", "год"], as_index=False)
        .agg(
            население_млн=("население_млн", "mean"),
            занятость_тыс=("занятость_тыс", "sum"),
            ВРП_млрд=("ВРП_млрд", "sum"),
            инвестиции_млрд=("инвестиции_млрд", "sum"),
            средняя_зп_тыс=("средняя_з/п_тыс", "mean"),
        )
    )
    agg["производительность_млн_на_чел"] = (
        agg["ВРП_млрд"] * 1e3 / agg["занятость_тыс"]
    )
    return agg
