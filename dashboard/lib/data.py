"""Генератор синтетического панельного датасета по 20 агломерациям РФ.

Данные приближены по порядку величин к реальным показателям Росстата
(численность населения, ВРП крупнейших городов), но являются синтетическими
и предназначены только для демонстрации аналитики.

Структура панели: (город × год × отрасль) → {занятость, ВРП, зарплата, инвестиции}.
"""
from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import pandas as pd
import streamlit as st

