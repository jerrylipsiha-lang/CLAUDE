"""Страница: методология — определения индексов и формулы."""
from __future__ import annotations

import streamlit as st

st.title("Методология")
st.markdown(
    '<p class="section-caption">Определения индексов, формулы и интерпретация</p>',
    unsafe_allow_html=True,
)

with st.expander("Источник данных", expanded=True):
    st.markdown(
        "Все показатели на этих страницах — **синтетические**, сгенерированы в "
        "`lib/data.py` с фиксированным seed. Структура (город × год × отрасль), "
        "порядки величин приближены к реальным открытым данным Росстата и ЕМИСС. "
        "Для реального исследования замените функцию `build_panel()` на загрузку "
        "CSV/Parquet из внешних источников."
    )

st.subheader("Индекс Херфиндаля–Хиршмана (HHI)")
st.latex(r"HHI = 10000 \cdot \sum_{i=1}^{N} s_i^2, \quad s_i = \frac{x_i}{\sum_j x_j}")
st.markdown(
    "Интерпретация: < 1500 — низкая концентрация; 1500–2500 — умеренная; "
    "> 2500 — высокая. Применяется, например, для антимонопольной оценки рынков "
    "(US DOJ, ФАС)."
)

st.subheader("Коэффициент Джини")
st.latex(r"G = \frac{2 \sum_{i=1}^{N} i \cdot x_{(i)}}{N \sum_{i=1}^{N} x_i} - \frac{N+1}{N}")
st.markdown(
    "Здесь $x_{(i)}$ — отсортированное по возрастанию значение. "
    "0 — полное равенство, 1 — максимальное неравенство."
)

st.subheader("Индекс Тейла")
st.latex(r"T = \frac{1}{N} \sum_{i=1}^{N} \frac{x_i}{\bar{x}} \ln \frac{x_i}{\bar{x}}")
st.markdown(
    "Важное свойство — **аддитивная декомпозиция**: общее неравенство раскладывается "
    "на «внутри групп» и «между группами», что удобно для пространственного анализа "
    "(например, неравенство между ФО и внутри ФО)."
)

st.subheader("Индекс локализации (Location Quotient, LQ)")
st.latex(r"LQ_{ij} = \frac{E_{ij}/E_i}{E_j/E}")
st.markdown(
    "$E_{ij}$ — занятость в городе $i$ и отрасли $j$; $E_i$ — всего в городе; "
    "$E_j$ — всего в отрасли по стране; $E$ — суммарная занятость. "
    "LQ > 1.25 — выраженная специализация."
)

st.subheader("Shift-share декомпозиция")
st.latex(r"""
\Delta E_i =
\underbrace{E_{i,0} \cdot g^{nat}}_{\text{NS}} +
\underbrace{\sum_j E_{ij,0}(g_j^{nat} - g^{nat})}_{\text{IM}} +
\underbrace{\sum_j E_{ij,0}(g_{ij} - g_j^{nat})}_{\text{CS}}
""")
st.markdown(
    "**NS** (national share) — общий рост страны; "
    "**IM** (industry mix) — выигрыш/проигрыш от структуры отраслей; "
    "**CS** (competitive shift) — уникальное локальное преимущество города."
)

st.subheader("Правило Ципфа (rank-size)")
st.latex(r"\ln(\text{rank}_i) = a - \beta \cdot \ln(\text{size}_i)")
st.markdown(
    "Классическая формулировка: $\\beta \\approx 1$. "
    "Значение β > 1 означает гипертрофию лидера (крупнейший город непропорционально велик), "
    "β < 1 — более равномерное распределение городов по размеру."
)

st.subheader("Кривая Лоренца")
st.markdown(
    "Строится как кумулятивная доля объёма (ось Y) от кумулятивной доли объектов (ось X). "
    "Площадь между линией равенства и кривой Лоренца пропорциональна коэффициенту Джини."
)

